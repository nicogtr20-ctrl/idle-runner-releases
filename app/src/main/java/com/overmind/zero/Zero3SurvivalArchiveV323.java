package com.overmind.zero;

import java.io.*;
import java.nio.file.*;
import java.security.MessageDigest;
import java.util.*;

/**
 * V3.23: same immutable commit contains existing V322B full neural/physics/
 * world/RNG/PRE+12 actions+POST and real observed metabolism per decision.
 * This is a lab-only container, not an Android profile migration.
 */
public final class Zero3SurvivalArchiveV323 {
    static final int MAGIC=0x5A333233,VERSION=323,MAX=8*1024*1024;
    public static final class Bundle{
        public final Zero3FullArchiveStoreV322B.Bundle joint;
        public final Zero3SurvivalLedgerV323.State survival;
        Bundle(Zero3FullArchiveStoreV322B.Bundle brain,
               Zero3SurvivalLedgerV323.State metabolism)throws IOException{
            if(brain==null||metabolism==null||
               brain.organism.nextDecision!=metabolism.next||
               brain.experienceCount()!=metabolism.next)
                throw new IOException("V323 torn neural/physical/metabolic decision cursor");
            Zero3OrganismStoreV322.Trace[] events=brain.organism.trace();
            for(int n=0;n<metabolism.next;n++){
                Zero3SurvivalLedgerV323.Trace e=metabolism.history.get(n);
                if(e.decision!=n||e.startTick!=events[n].startTick||
                   e.endTick!=events[n].endTick)
                    throw new IOException("metabolism not generated by this physical transition");
            }
            joint=brain;survival=metabolism;
        }
    }
    static byte[] encode(Bundle b)throws IOException{
        if(b==null)throw new IOException("empty organism bundle");
        ByteArrayOutputStream bytes=new ByteArrayOutputStream();
        DataOutputStream out=new DataOutputStream(bytes);
        byte[] physique=Zero3FullArchiveStoreV322B.encode(b.joint);
        byte[] energy=b.survival.encoded();
        out.writeInt(MAGIC);out.writeInt(VERSION);
        out.writeInt(physique.length);out.write(physique);
        out.writeInt(energy.length);out.write(energy);out.flush();
        if(bytes.size()>MAX)throw new IOException("too much live replay for single 8MiB commit");
        return bytes.toByteArray();
    }
    static Bundle decode(byte[] data)throws IOException{
        if(data==null||data.length<500||data.length>MAX)
            throw new IOException("snapshot length invalid");
        try{
            DataInputStream input=new DataInputStream(new ByteArrayInputStream(data));
            if(input.readInt()!=MAGIC||input.readInt()!=VERSION)
                throw new IOException("bad version of combined metabolic snapshot");
            int n=input.readInt();
            if(n<200||n>MAX-512)throw new IOException("bad physical replay length");
            byte[] j=new byte[n];input.readFully(j);
            int m=input.readInt();
            if(m<53||m>262144||input.available()!=m)
                throw new IOException("metabolic record length mismatch");
            byte[] t=new byte[m];input.readFully(t);
            return new Bundle(Zero3FullArchiveStoreV322B.decode(j),
                              Zero3SurvivalLedgerV323.State.decoded(t));
        }catch(IllegalStateException|IllegalArgumentException x){
            throw new IOException("V323 invalid checkpoint fields",x);
        }
    }
    private static byte[] sha(byte[] payload){
        try{return MessageDigest.getInstance("SHA-256").digest(payload);}
        catch(Exception e){throw new IllegalStateException(e);}
    }
    public static String fingerprint(Bundle bundle)throws IOException{
        StringBuilder b=new StringBuilder();
        for(byte x:sha(encode(bundle)))b.append(String.format("%02x",x&255));
        return b.toString();
    }
    private final Path dir;
    private int active=-1;
    private long generation;
    private byte[] verified;
    public Zero3SurvivalArchiveV323(Path root){
        if(root==null)throw new IllegalArgumentException("lab path missing");
        dir=root;
    }
    private Path data(int s){return dir.resolve("v323-life-"+s+".bin");}
    private Path manifest(boolean current){
        return dir.resolve(current?"v323-current.mf":"v323-previous.mf");
    }
    private static void atomic(Path target,byte[] contents)throws IOException{
        Path temp=target.resolveSibling(target.getFileName()+".tmp");
        try{
            try(FileOutputStream f=new FileOutputStream(temp.toFile())){
                f.write(contents);f.flush();f.getFD().sync();
            }
            Files.move(temp,target,StandardCopyOption.ATOMIC_MOVE,
                       StandardCopyOption.REPLACE_EXISTING);
        }finally{Files.deleteIfExists(temp);}
    }
    private static byte[] pointer(int s,long gen,byte[] raw)throws IOException{
        ByteArrayOutputStream buffer=new ByteArrayOutputStream(88);
        DataOutputStream o=new DataOutputStream(buffer);
        o.writeInt(MAGIC);o.writeInt(VERSION);o.writeInt(s);o.writeLong(gen);
        o.writeInt(raw.length);o.write(sha(raw));o.flush();
        o.write(sha(buffer.toByteArray()));o.flush();return buffer.toByteArray();
    }
    private static final class Recovery{
        final int s;final long g;final byte[] raw;final Bundle bundle;
        Recovery(int s,long g,byte[] raw,Bundle bundle){
            this.s=s;this.g=g;this.raw=raw;this.bundle=bundle;
        }
    }
    private Recovery inspect(Path p)throws IOException{
        byte[] m=Files.readAllBytes(p);
        if(m.length!=88||!Arrays.equals(sha(Arrays.copyOf(m,56)),
                    Arrays.copyOfRange(m,56,88)))throw new IOException("bad manifest SHA");
        DataInputStream in=new DataInputStream(new ByteArrayInputStream(m));
        if(in.readInt()!=MAGIC||in.readInt()!=VERSION)
            throw new IOException("manifest wrong version");
        int s=in.readInt();long g=in.readLong();int size=in.readInt();
        byte[] expected=new byte[32];in.readFully(expected);
        if((s!=0&&s!=1)||g<=0||size<500||size>MAX)
            throw new IOException("invalid generation metadata");
        byte[] raw=Files.readAllBytes(data(s));
        if(raw.length!=size||!Arrays.equals(sha(raw),expected))
            throw new IOException("corrupt or mixed generation");
        return new Recovery(s,g,raw,decode(raw));
    }
    public Bundle load()throws IOException{
        Recovery r=null;
        try{r=inspect(manifest(true));}catch(IOException ignored){}
        if(r==null)try{r=inspect(manifest(false));}catch(IOException ignored){}
        if(r==null){active=-1;generation=0;verified=null;return null;}
        active=r.s;generation=r.g;verified=r.raw;return r.bundle;
    }
    public void save(Bundle bundle)throws IOException{
        byte[] raw=encode(bundle);
        if(!Arrays.equals(raw,encode(decode(raw))))
            throw new IOException("noncanonical joint body/brain/metabolic replay");
        Files.createDirectories(dir);
        if(generation>0&&(verified==null||
            !Arrays.equals(Files.readAllBytes(data(active)),verified)))
            throw new IOException("last validated generation unexpectedly changed");
        int next=active==0?1:0;
        atomic(data(next),raw);
        if(generation>0)atomic(manifest(false),pointer(active,generation,verified));
        atomic(manifest(true),pointer(next,generation+1,raw));
        active=next;generation++;verified=raw;
    }
    public long generation(){return generation;}
    public Path latestFile(){return data(active);}
    public Path olderFile(){return data(1-active);}
    public Path currentManifest(){return manifest(true);}
}
